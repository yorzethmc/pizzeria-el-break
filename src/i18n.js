function pick(obj, field, lang) {
  if (lang === "en") {
    const enField = `${field}En`;
    if (obj[enField]) return obj[enField];
  }
  if (lang === "pt") {
    const ptField = `${field}Pt`;
    if (obj[ptField]) return obj[ptField];
  }
  return obj[field];
}

function localizeOption(option, lang) {
  return {
    ...option,
    name: pick(option, "name", lang)
  };
}

function localizeItem(item, lang) {
  const localized = {
    ...item,
    name: pick(item, "name", lang),
    description: pick(item, "description", lang),
    options: item.options.map((option) => localizeOption(option, lang)),
    extras: (item.extras || []).map((extra) => localizeOption(extra, lang))
  };
  if (item.section) {
    localized.section = pick(item, "section", lang);
  }
  return localized;
}

export function localizeCategories(categories, lang) {
  return categories.map((category) => ({
    ...category,
    name: pick(category, "name", lang),
    shortName: pick(category, "shortName", lang),
    items: category.items.map((item) => localizeItem(item, lang))
  }));
}
